/** Maps a dependency/manifest signal to a skill slug from packages/db/src/seed/skills.ts. */
export interface DepSignal {
  ecosystem: 'npm' | 'pypi' | 'go' | 'cargo' | 'maven' | 'gem' | 'pub' | 'nuget' | 'platformio' | 'file';
  name: string;
  skill: string;
  weight?: number;
}

type Eco = DepSignal['ecosystem'];
/** Build entries for one ecosystem: [name, skill, weight?] tuples. */
const group = (ecosystem: Eco, rows: Array<[string, string, number?]>): DepSignal[] =>
  rows.map(([name, skill, weight]) =>
    weight === undefined ? { ecosystem, name, skill } : { ecosystem, name, skill, weight },
  );

