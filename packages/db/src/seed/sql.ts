/**
 * Renders the skill taxonomy and event templates as idempotent SQL for a D1 migration.
 * `pnpm --filter @hakit/db seed:sql > migrations/NNNN_seed.sql` after `drizzle-kit generate --custom`.
 * Upserts by slug, so re-running a newer seed updates names, aliases and challenges in place.
 * Embeddings are not computed here; the worker's `embed.batch` job fills skills.embedding.
 */
import { pathToFileURL } from 'node:url';
import { HACKATHONS } from './hackathons';
import { SKILLS } from './skills';

const q = (v: string | null | undefined) => (v == null ? 'NULL' : `'${v.replace(/'/g, "''")}'`);
const j = (v: unknown) => q(JSON.stringify(v));
/** Random v4 UUID, evaluated by SQLite. */
const UUID = `(lower(hex(randomblob(4))) || '-' || lower(hex(randomblob(2))) || '-4' || substr(lower(hex(randomblob(2))), 2) || '-' || substr('89ab', 1 + (abs(random()) % 4), 1) || substr(lower(hex(randomblob(2))), 2) || '-' || lower(hex(randomblob(6))))`;

export function seedSql(): string {
  const out = ['-- Generated by packages/db/src/seed/sql.ts. Skill taxonomy and event templates.'];
  for (const s of SKILLS)
    out.push(
      `INSERT INTO skills (id, slug, name, category, aliases, related) VALUES (${UUID}, ${q(s.slug)}, ${q(s.name)}, ${q(s.category)}, ${j(s.aliases)}, ${j(s.related ?? [])})
  ON CONFLICT(slug) DO UPDATE SET name = excluded.name, category = excluded.category, aliases = excluded.aliases, related = excluded.related;`,
    );
  for (const h of HACKATHONS) {
    out.push(
      `INSERT INTO hackathon_templates (id, slug, name, starts_at, ends_at, timezone, tracks, judging_criteria, source_url) VALUES (${UUID}, ${q(h.slug)}, ${q(h.name)}, ${Date.parse(h.startsAt)}, ${Date.parse(h.endsAt)}, ${q(h.timezone)}, ${j(h.tracks)}, ${j(h.judgingCriteria)}, ${q(h.sourceUrl)})
  ON CONFLICT(slug) DO UPDATE SET name = excluded.name, starts_at = excluded.starts_at, ends_at = excluded.ends_at, tracks = excluded.tracks, judging_criteria = excluded.judging_criteria;`,
    );
    for (const c of h.challenges)
      out.push(
        `INSERT INTO challenges (id, hackathon_template_id, key, sponsor, title, requirements, required_tech) VALUES (${UUID}, (SELECT id FROM hackathon_templates WHERE slug = ${q(h.slug)}), ${q(c.key)}, ${q(c.sponsor)}, ${q(c.title)}, ${j([...c.requirements])}, ${j([...c.requiredTech])})
  ON CONFLICT(hackathon_template_id, key) DO UPDATE SET sponsor = excluded.sponsor, title = excluded.title, requirements = excluded.requirements, required_tech = excluded.required_tech;`,
      );
  }
  return out.join('\n--> statement-breakpoint\n') + '\n';
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) process.stdout.write(seedSql());
